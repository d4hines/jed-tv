#!/usr/bin/env python3
"""Generate the Lean test-vector modules in CryptoTest/Vec*.lean.

Inputs (downloaded once, kept in the git-ignored assets tree):
  assets/build/lean-tls/rfc/rfc{4231,5869}.txt   (rfc-editor.org)
  assets/build/lean-tls/wycheproof/*.json   (github.com/C2SP/wycheproof, testvectors_v1)

Each module holds one string, one vector per line, space-separated fields
("-" for an empty field): `id result field...`, result v (valid), i
(invalid) or a (acceptable). Wycheproof subsets keep every distinct
(flags, result) combination and fill up to a cap with a fixed stride.

    python3 -I test/lean/yt/crypto/gen_vectors.py
"""
import hashlib, hmac, json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
RFC = ROOT / "assets/build/lean-tls/rfc"
WP = ROOT / "assets/build/lean-tls/wycheproof"
OUT = HERE / "CryptoTest"


def emit(name, doc, lines):
    body = "\n".join(lines)
    assert '"' not in body and "\\" not in body
    (OUT / f"{name}.lean").write_text(
        f"/-! {doc} Generated by ../gen_vectors.py; do not edit. -/\n"
        f"namespace CryptoTest.{name}\n"
        f"def data : String := \"{body}\"\nend CryptoTest.{name}\n")
    print(f"{name}: {len(lines)} vectors")


def f(x):
    return x if x else "-"


def rfc_fields(text, start, end):
    """`Name = hex` fields of an RFC section (hex may wrap onto following lines)."""
    sec = text[text.index(start):text.index(end, text.index(start))]
    fields, cur = {}, None
    for line in sec.splitlines():
        m = re.match(r"\s{2,}([A-Za-z][A-Za-z0-9 \-]*?)\s*=\s*(?:0x)?([0-9a-fA-F]*)", line)
        if m:
            cur = m.group(1).strip()
            fields[cur] = m.group(2).lower()
            continue
        m = re.match(r"\s{10,}(?:0x)?([0-9a-f]+)(\s|$)", line)
        if m and cur:
            fields[cur] += m.group(1)
        elif not line.strip().startswith("("):
            cur = None if line.strip() and not re.match(r"\s{10,}", line) else cur
    return fields


def hmac_vectors():
    t = (RFC / "rfc4231.txt").read_text()
    lines = []
    for n, (s, e) in enumerate([("4.2.  Test Case 1", "4.3."), ("4.3.  Test Case 2", "4.4."),
                                ("4.4.  Test Case 3", "4.5."), ("4.5.  Test Case 4", "4.6."),
                                ("4.7.  Test Case 6", "4.8."), ("4.8.  Test Case 7", "5.  Security")], 1):
        s, e = "\n" + s, "\n" + e
        sec = t[t.index(s):t.index(e, t.index(s) + 10)]
        sec = re.sub(r"\n\nNystrom.*?\n\nRFC 4231.*?\n", "\n", sec, flags=re.S)
        fields, cur = {}, None
        for line in sec.splitlines():
            m = re.match(r"   (Key|Data|HMAC-SHA-\d+)\s*=?\s+([0-9a-f]+)", line)
            if m:
                cur = m.group(1)
                fields[cur] = m.group(2)
            elif cur and re.match(r"\s{18}[0-9a-f]+", line):
                fields[cur] += line.split()[0]
            else:
                cur = None
        def grab(label):
            return fields[label]
        key, data = grab("Key"), grab("Data")
        for alg, hname in [("sha256", "HMAC-SHA-256"), ("sha384", "HMAC-SHA-384"), ("sha512", "HMAC-SHA-512")]:
            mac = grab(hname)
            want = hmac.new(bytes.fromhex(key), bytes.fromhex(data), alg).hexdigest()
            assert want == mac, (n, alg)
            lines.append(f"{n} v {alg} {key} {data} {mac}")
    emit("VecHmac", "RFC 4231 HMAC-SHA-256/384/512 test cases 1-4, 6, 7.", lines)


def hkdf_vectors():
    t = (RFC / "rfc5869.txt").read_text()
    lines = []
    for n, (s, e) in enumerate([("A.1.  Test Case 1", "A.2."), ("A.2.  Test Case 2", "A.3."),
                                ("A.3.  Test Case 3", "A.4.")], 1):
        s, e = "\n" + s, "\n" + e
        sec = t[t.index(s):t.index(e, t.index(s) + 10)]
        sec = re.sub(r"\n\nKrawczyk.*?\n\nRFC 5869.*?\n", "\n", sec, flags=re.S)
        def grab(label):
            m = re.search(label + r"\s*=\s*(?:0x((?:[0-9a-f]+\s*)+)|\(0 octets\))", sec)
            return re.sub(r"\s", "", m.group(1) or "") if m.group(1) else ""
        ikm, salt, info = grab("IKM"), grab("salt"), grab("info")
        L = int(re.search(r"L\s*=\s*(\d+)", sec).group(1))
        prk, okm = grab("PRK"), grab("OKM")
        assert hmac.new(bytes.fromhex(salt) or bytes(32), bytes.fromhex(ikm), "sha256").hexdigest() == prk
        lines.append(f"{n} v {f(ikm)} {f(salt)} {f(info)} {L} {prk} {okm}")
    emit("VecHkdf", "RFC 5869 HKDF-SHA-256 test cases 1-3.", lines)


def pick(tests, cap):
    """Every distinct (flags, result) once, then a fixed stride up to `cap`."""
    seen, chosen = set(), []
    for t in tests:
        k = (tuple(t[0].get("flags", [])), t[0]["result"])
        if k not in seen:
            seen.add(k)
            chosen.append(t)
    rest = [t for t in tests if t not in chosen]
    room = max(0, cap - len(chosen))
    if room and rest:
        step = max(1, len(rest) // room)
        chosen += rest[::step][:room]
    return sorted(chosen, key=lambda t: t[0]["tcId"])


def res(r):
    return {"valid": "v", "invalid": "i", "acceptable": "a"}[r]


def aead(file, name, doc, cap, keep):
    d = json.loads((WP / file).read_text())
    tests = [(t, g) for g in d["testGroups"] if keep(g) for t in g["tests"]]
    lines = [f"{t['tcId']} {res(t['result'])} {f(t['key'])} {f(t['iv'])} {f(t['aad'])} {f(t['msg'])} "
             f"{f(t['ct'])} {t['tag']}" for t, g in pick(tests, cap)]
    emit(name, doc, lines)


def x25519():
    d = json.loads((WP / "x25519_test.json").read_text())
    tests = [(t, g) for g in d["testGroups"] for t in g["tests"]]
    lines = [f"{t['tcId']} {res(t['result'])} {t['private']} {t['public']} {t['shared']}"
             for t, g in pick(tests, 120)]
    emit("VecX25519", "Wycheproof x25519_test.json subset (Montgomery-ladder X25519).", lines)


def ecdsa(file, name, doc, cap):
    d = json.loads((WP / file).read_text())
    tests = [(t, g) for g in d["testGroups"] for t in g["tests"]]
    lines = [f"{t['tcId']} {res(t['result'])} {g['publicKey']['uncompressed']} {f(t['msg'])} {f(t['sig'])}"
             for t, g in pick(tests, cap)]
    emit(name, doc, lines)


def rsa(file, name, doc, cap):
    d = json.loads((WP / file).read_text())
    tests = [(t, g) for g in d["testGroups"] for t in g["tests"]]
    lines = []
    for t, g in pick(tests, cap):
        pk = g["publicKey"]
        lines.append(f"{t['tcId']} {res(t['result'])} {pk['modulus']} {pk['publicExponent']} {f(t['msg'])} {f(t['sig'])}")
    emit(name, doc, lines)


if __name__ == "__main__":
    hmac_vectors()
    hkdf_vectors()
    aead("aes_gcm_test.json", "VecAesGcm", "Wycheproof aes_gcm_test.json subset (128/256-bit keys, 96-bit IV, 128-bit tag).",
         140, lambda g: g["ivSize"] == 96 and g["tagSize"] == 128 and g["keySize"] in (128, 256))
    aead("chacha20_poly1305_test.json", "VecChaCha", "Wycheproof chacha20_poly1305_test.json subset (96-bit nonce).",
         100, lambda g: g["ivSize"] == 96)
    x25519()
    ecdsa("ecdsa_secp256r1_sha256_test.json", "VecP256", "Wycheproof ecdsa_secp256r1_sha256_test.json subset (DER signatures).", 140)
    ecdsa("ecdsa_secp384r1_sha384_test.json", "VecP384", "Wycheproof ecdsa_secp384r1_sha384_test.json subset (DER signatures).", 120)
    rsa("rsa_signature_2048_sha256_test.json", "VecRsa2048", "Wycheproof rsa_signature_2048_sha256_test.json subset (PKCS#1 v1.5).", 50)
    rsa("rsa_signature_4096_sha384_test.json", "VecRsa4096", "Wycheproof rsa_signature_4096_sha384_test.json subset (PKCS#1 v1.5).", 25)
    rsa("rsa_pss_2048_sha256_mgf1_32_test.json", "VecPss2048", "Wycheproof rsa_pss_2048_sha256_mgf1_32_test.json subset.", 40)
    rsa("rsa_pss_4096_sha512_mgf1_64_test.json", "VecPss4096", "Wycheproof rsa_pss_4096_sha512_mgf1_64_test.json subset.", 20)
