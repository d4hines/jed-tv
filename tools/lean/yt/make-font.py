#!/usr/bin/env python3
"""Rasterize DejaVu Sans into glyph blobs for the Lean UI (Yt/Ui/FontData.lean).

The TV binary then contains only coverage masks and metrics, no font code:
rasterization happens here, on the build host, with Pillow (FreeType).

    nix shell --impure --expr 'let p = import (builtins.getFlake "nixpkgs") { system = builtins.currentSystem; }; in p.python3.withPackages (ps: [ ps.pillow ])' \
      -c python3 tools/lean/yt/make-font.py

Blob layout (little-endian): "YTF1", u32 glyph count, u16 pixel size,
u16 ascent, u16 line height, u16 0; then 16-byte records sorted by code point
(u32 code point, u32 mask offset, u8 width, u8 height, i8 x offset, i8 y offset
from the line top, u8 advance, 3 zero bytes); then the 8-bit masks.
"""
import base64, pathlib, struct
from PIL import ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[3]
FONT = ROOT / 'src/slides/fonts/dejavu-2.37/DejaVuSans.ttf'
OUT = ROOT / 'src/lean/yt/Yt/Ui/FontData.lean'
SIZES = [22, 28, 40]
EXTRA = [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC, 0x2122,
         0x2016, 0x25B6, 0x25C0, 0x2423, 0x232B]
CODES = list(range(32, 127)) + list(range(160, 256)) + EXTRA


def blob(size):
    font = ImageFont.truetype(str(FONT), size)
    ascent, descent = font.getmetrics()
    records, masks = [], bytearray()
    for cp in sorted(CODES):
        ch = chr(cp)
        mask, (xo, yo) = font.getmask2(ch, mode='L')
        w, h = mask.size
        data = bytes(mask) if w and h else b''
        adv = round(font.getlength(ch))
        if not (-128 <= xo < 128 and -128 <= yo < 128 and w < 256 and h < 256 and adv < 256):
            raise SystemExit(f'glyph U+{cp:04X} at {size}px does not fit the record')
        records.append(struct.pack('<IIBBbbBxxx', cp, len(masks), w, h, xo, yo, adv))
        masks += data
    head = b'YTF1' + struct.pack('<IHHHH', len(records), size, ascent, ascent + descent, 0)
    return head + b''.join(records) + bytes(masks)


def main():
    lines = ['/-! Generated by tools/lean/yt/make-font.py from DejaVu Sans 2.37',
             '(src/slides/fonts/dejavu-2.37, free license there). Do not edit:',
             'rerun the script. Base64 glyph blobs; see Yt/Ui/Text.lean. -/',
             'namespace Yt.Ui.FontData', '']
    for size in SIZES:
        b = blob(size)
        lines.append(f'/-- DejaVu Sans {size}px ({len(b)} bytes). -/')
        lines.append(f'def sans{size} : String := "{base64.b64encode(b).decode()}"')
        lines.append('')
        print(f'{size}px: {len(b)} bytes')
    lines.append('end Yt.Ui.FontData')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
