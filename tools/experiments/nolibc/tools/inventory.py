#!/usr/bin/env python3
"""Symbol inventory for the rest of the apps (gate 2 of research/nolibc-brief.md).

  python3 nolibc/tools/inventory.py

For each target: link-level probes (tools/probe_undefined.py) of tvinit,
slides, ytplay and doomtv against an empty libc and against nolibc-rt, plus
archive-level imports (tools/archive_imports.py) of the foreign pieces:
doomgeneric (C) and ffh264 (FFmpeg's H.264 decoder translated to Rust by
c2rust, which still calls libc). Writes assets/build/nolibc/inventory/ and
SUMMARY.md, which splits each program's still-missing symbols into those the
foreign piece imports and the rest (std + other crates).
"""
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import build as B  # noqa: E402

INV = B.BUILD / "inventory"


def foreign(target):
    """name -> archive files; ffh264's rlib comes from the probe build itself."""
    deps = B.BUILD / "target-probe-empty" / target / "release" / "deps"
    return {
        "doomgeneric": [B.ROOT / "assets/build/doom" / target / "libdoomgeneric.a"],
        "ffh264": sorted(deps.glob("libffh264-*.rlib"))[-1:],
    }


def short(t):
    return "armv7" if t.startswith("armv7") else "aarch64"


def probe(binname, target, against):
    out = INV / f"{binname}-{short(target)}{'-missing' if against == 'nolibc' else ''}.txt"
    subprocess.run([sys.executable, HERE / "probe_undefined.py", binname, target, "--against", against,
                    "--out", out], check=True)
    # Weak references (std's optional __cxa_thread_atexit_impl, gettid, ...) resolve to null; std copes.
    return [l.split()[0] for l in out.read_text().splitlines() if l.strip() and "(weak)" not in l]


def archive(name, target, files):
    if not files or not all(f.exists() for f in files):
        return None
    out = INV / f"{name}-{short(target)}.md"
    r = subprocess.run([sys.executable, HERE / "archive_imports.py", f"{name} ({target})", out, *files],
                       capture_output=True, text=True, check=True).stdout.splitlines()
    return r[1].split() if len(r) > 1 else []


def main():
    lines = ["# nolibc symbol inventory", "",
             "Generated by `nolibc/tools/inventory.py`. *imports* = strong undefined symbols when linked against",
             "an empty libc; *missing* = still undefined when linked against nolibc-rt",
             "(`--unresolved-symbols=ignore-all`, read back with `llvm-nm -u`; weak references omitted).", ""]
    for t in B.TARGETS:
        lines += [f"## {t}", ""]
        found = {}
        for binname, piece in (("tvinit", None), ("slides", None), ("ytplay", "ffh264"), ("doomtv", "doomgeneric")):
            imp = probe(binname, t, "empty")
            miss = probe(binname, t, "nolibc")
            psyms = archive(piece, t, foreign(t)[piece]) if piece else None
            if psyms is not None:
                found[piece] = psyms
            lines.append(f"### {binname}: imports {len(imp)}, missing with nolibc-rt {len(miss)}")
            if piece:
                from_p = [s for s in miss if s in set(psyms or [])]
                lines.append(f"- imported by {piece} ({len(from_p)}): `{' '.join(from_p)}`")
                miss = [s for s in miss if s not in set(psyms or [])]
            lines.append(f"- imported by std and other crates ({len(miss)}): `{' '.join(miss)}`")
            lines.append("")
        for name, syms in found.items():
            lines.append(f"- {name} archive-level imports ({len(syms)}): `{' '.join(syms)}`")
        lines.append("")
    (INV / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
