#!/usr/bin/env python3
"""Generate Doom/Playsim/Defs.lean (MT_/S_/SPR_/sfx_/mus_ ordinals) from the
Chocolate Doom oracle headers info.h and sounds.h.

usage: gen_defs.py ORACLE_SRC_DOOM_DIR OUT.lean
"""
import re, sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
info = (src / "info.h").read_text()
sounds = (src / "sounds.h").read_text()

def enum_body(text, first, sentinel):
    m = re.search(r"typedef enum\s*\{([^}]*?\b" + first + r"\b[^}]*?)\b" + sentinel + r"\b", text)
    if not m:
        raise SystemExit(f"enum {first} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    names = [t.strip() for t in body.split(",")]
    return [n for n in names if n]

groups = [
    ("SPR", enum_body(info, "SPR_TROO", "NUMSPRITES"), "UInt32"),
    ("S", enum_body(info, "S_NULL", "NUMSTATES"), "UInt32"),
    ("MT", enum_body(info, "MT_PLAYER", "NUMMOBJTYPES"), "Int32"),
    ("sfx", enum_body(sounds, "sfx_None", "NUMSFX"), "Nat"),
    ("mus", enum_body(sounds, "mus_None", "NUMMUSIC"), "Nat"),
]
lines = ["/-! Ordinals of the oracle `info.h` / `sounds.h` enums.",
         "GENERATED by scripts/gen_defs.py from the Chocolate Doom oracle; do not edit. -/",
         "", "namespace Doom.Playsim.Defs", ""]
for prefix, names, ty in groups:
    for i, n in enumerate(names):
        if "=" in n:
            raise SystemExit(f"explicit value in {n}")
        lines.append(f"@[inline] def {n} : {ty} := {i}")
    lines.append("")
lines.append("end Doom.Playsim.Defs")
out.write_text("\n".join(lines) + "\n")
print({p: len(n) for p, n, _ in groups})
