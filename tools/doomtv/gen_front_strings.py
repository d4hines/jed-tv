#!/usr/bin/env python3
"""Generate Doom/Front/Strings.lean from the oracle's d_englsh.h.

Usage: gen_front_strings.py ORACLE_DOOM_DIR > Doom/Front/Strings.lean
"""
import re
import sys

src = open(sys.argv[1] + "/d_englsh.h", encoding="latin1").read()
# Join continuation lines, then collect each #define NAME "..." "..."
src = src.replace("\\\n", " ")
defs = {}
for m in re.finditer(r'^#define\s+(\w+)\s+((?:"(?:[^"\\]|\\.)*"\s*)+)\s*$', src, re.M):
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))
    s = "".join(parts)
    s = bytes(s, "latin1").decode("unicode_escape")
    defs[m.group(1)] = s

def lean_str(s):
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        else: out.append(ch)
    return '"' + "".join(out) + '"'

def table(name, keys, doc):
    lines = [f"/-- {doc} -/", f"def {name} : Array (String × String) := #["]
    for i, k in enumerate(keys):
        sep = "," if i + 1 < len(keys) else ""
        lines.append(f"  ({lean_str(k)}, {lean_str(defs[k])}){sep}")
    lines.append("]")
    return "\n".join(lines)

doom1 = [f"HUSTR_E{e}M{m}" for e in range(1, 5) for m in range(1, 10)]
doom2 = [f"HUSTR_{m}" for m in range(1, 33)]
cast = ["CC_ZOMBIE", "CC_SHOTGUN", "CC_HEAVY", "CC_IMP", "CC_DEMON", "CC_LOST",
        "CC_CACO", "CC_HELL", "CC_BARON", "CC_ARACH", "CC_PAIN", "CC_REVEN",
        "CC_MANCU", "CC_ARCH", "CC_SPIDER", "CC_CYBER", "CC_HERO"]
texts = ["E1TEXT", "E2TEXT", "E3TEXT", "E4TEXT",
         "C1TEXT", "C2TEXT", "C3TEXT", "C4TEXT", "C5TEXT", "C6TEXT"]
am = ["AMSTR_FOLLOWON", "AMSTR_FOLLOWOFF", "AMSTR_GRIDON", "AMSTR_GRIDOFF",
      "AMSTR_MARKEDSPOT", "AMSTR_MARKSCLEARED"]

print("""/-! English strings used by the front end, from the oracle `d_englsh.h`,
keyed by their BEX mnemonic (`deh_bexstr.c`).
GENERATED by scripts/gen_front_strings.py; do not edit by hand. -/

namespace Doom.Front.Strings
""")
print(table("mapnamesDoom", doom1, "`mapnames[]` (`hu_stuff.c`): E1M1..E4M9."))
print()
print(table("mapnamesCommercial", doom2, "`mapnames_commercial[0..31]` (`hu_stuff.c`): MAP01..MAP32."))
print()
print(table("castNames", cast, "`castorder[].name` (`f_finale.c`)."))
print()
print(table("finaleTexts", texts, "Finale texts E1..E4, C1..C6 (`f_finale.c` `textscreens`)."))
print()
print(table("automapStrings", am, "Automap messages (`am_map.c`)."))
print()
print("end Doom.Front.Strings")
